const {test} = require('node:test');
const assert = require('node:assert/strict');
const {readFileSync} = require('node:fs');
const {JSDOM} = require('jsdom');
const fonte = readFileSync(require.resolve('../js/seletores.js'), 'utf8');
function ambiente(t, html) {
    const dom = new JSDOM(html, {runScripts:'outside-only'});
    t.after(() => dom.window.close());
    dom.window.eval(fonte + '\nwindow.api = ForjaSeletores;');
    return {w:dom.window, d:dom.window.document, api:dom.window.api};
}
test('seletor preserva fonte, eventos, teclado, foco e opções indisponíveis', t => {
    const {w,d,api} = ambiente(t, '<label>Idioma<select required><option>Comum</option><option hidden>Oculto</option><optgroup disabled><option>Bloqueado</option></optgroup><option>Élfico</option></select></label>');
    const select = d.querySelector('select');
    let mudancas = 0;
    select.addEventListener('change', () => mudancas++);
    api.instalar();
    const botao = d.querySelector('.forja-seletor-botao');
    assert.equal(botao.getAttribute('aria-label'), 'Escolher Idioma: Comum');
    assert.equal(select.required, true);
    botao.click();
    assert.equal(d.querySelectorAll('[role=option]').length, 3);
    assert.equal(d.querySelectorAll('[role=option]:disabled').length, 1);
    const busca = d.querySelector('input');
    busca.dispatchEvent(new w.KeyboardEvent('keydown', {key:'ArrowUp', bubbles:true}));
    assert.equal(d.activeElement.textContent, 'Élfico');
    d.activeElement.click();
    assert.equal(select.value, 'Élfico');
    assert.equal(mudancas, 1);
    assert.equal(d.querySelector('dialog'), null);
    assert.equal(d.activeElement, botao);
    select.value = 'Comum';
    select.dispatchEvent(new w.Event('change', {bubbles:true}));
    assert.equal(botao.textContent, 'Idioma: Comum');
});
test('opções dinâmicas e entrada fechada pesquisam texto sem interpretar HTML', async t => {
    const {w,d,api} = ambiente(t, '<label>Arma<input id="arma"></label><div id="alvo"></div>');
    api.instalar();
    const input = d.querySelector('input');
    api.entrada(input, ['Adaga', '<img src=x>']);
    assert.equal(input.readOnly, true);
    d.querySelector('.forja-seletor-botao').click();
    const busca = d.querySelector('.forja-seletor-busca');
    busca.value = 'img';
    busca.dispatchEvent(new w.Event('input'));
    assert.equal(d.querySelectorAll('[role=option]').length, 1);
    assert.equal(d.querySelector('img'), null);
    busca.dispatchEvent(new w.KeyboardEvent('keydown', {key:'Enter', bubbles:true}));
    assert.equal(input.value, '<img src=x>');
    d.querySelector('#alvo').innerHTML = '<label>Classe<select><option>Mago</option></select></label>';
    await new Promise(resolve => w.setTimeout(resolve, 0));
    assert.equal(d.querySelectorAll('.forja-seletor-botao').length, 2);
    const select = d.querySelector('select');
    select.disabled = true;
    await new Promise(resolve => w.setTimeout(resolve, 0));
    assert.equal(select.nextElementSibling.disabled, true);
    select.closest('label').remove();
    await new Promise(resolve => w.setTimeout(resolve, 0));
    assert.equal(d.querySelectorAll('.forja-seletor-botao').length, 1);
});
test('Escape fecha somente o seletor e restaura foco dentro do diálogo pai', t => {
    const {w,d,api} = ambiente(t, '<dialog open><label>Antecedente<select><option>Sábio</option></select></label></dialog>');
    api.instalar();
    const pai = d.querySelector('dialog');
    const botao = d.querySelector('button');
    botao.click();
    d.querySelector('.forja-seletor-busca').dispatchEvent(new w.KeyboardEvent('keydown', {key:'Escape', bubbles:true}));
    assert.equal(pai.open, true);
    assert.equal(d.querySelectorAll('dialog').length, 1);
    assert.equal(d.activeElement, botao);
});
